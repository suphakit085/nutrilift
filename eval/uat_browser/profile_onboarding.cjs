async(page)=>{
  const {origin,apiOrigin,artifactDir}=__AUTH_UAT_CONFIG__;
  const api='http://127.0.0.1:8026',email='onboarding@example.com',password='OnboardingTest_123!';
  const checks=[],errors=[];
  const add=(id,passed)=>{checks.push({id,passed});if(!passed)throw new Error(id);};
  page.setDefaultTimeout(20000);
  page.on('pageerror',error=>errors.push(error.message));
  await page.route(apiOrigin+'/**',async route=>{
    const request=route.request(),url=new URL(request.url());
    const response=await page.request.fetch(api+url.pathname+url.search,{method:request.method(),headers:{...request.headers(),host:'127.0.0.1:8026'},data:request.postDataBuffer()??undefined});
    await route.fulfill({response});
  });
  const login=async(destination)=>{
    await page.goto(origin+'/login');await page.locator('body').ariaSnapshot();
    await page.locator('input[name=email]').fill(email);
    await page.locator('input[name=password]').fill(password);
    await page.locator('button[type=submit]').click();
    await page.waitForURL('**'+destination);
  };
  await page.goto(origin+'/login');await page.locator('body').ariaSnapshot();
  await page.getByRole('button',{name:'สมัครสมาชิก',exact:true}).click();
  await page.locator('body').ariaSnapshot();
  await page.locator('input[name=email]').fill(email);
  for(const box of await page.getByRole('checkbox').all())await box.check();
  await page.getByRole('button',{name:'ส่งรหัสยืนยัน',exact:true}).click();
  await page.getByRole('heading',{name:'กรอกรหัสยืนยันอีเมล',exact:true}).waitFor();
  let code;
  for(let i=0;i<50;i++){
    const mail=await(await page.request.get(api+'/__test/mail')).json();
    code=mail.findLast(m=>m.to===email&&m.code)?.code;
    if(code)break;
    await page.waitForTimeout(100);
  }
  if(!code)throw new Error('No local SMTP OTP');
  await page.locator('input[name=email-code]').fill(code);
  await page.getByRole('button',{name:'ยืนยันรหัส',exact:true}).click();
  await page.getByRole('heading',{name:'ตั้งรหัสผ่านของคุณ',exact:true}).waitFor();
  await page.locator('body').ariaSnapshot();
  await page.locator('input[name=new-password]').fill(password);
  await page.locator('input[name=confirm-new-password]').fill(password);
  await page.getByRole('button',{name:'ตั้งรหัสผ่านและเริ่มใช้งาน',exact:true}).click();
  await page.waitForURL('**/profile');
  await page.getByText('กรอกโปรไฟล์และเป้าหมายก่อนเริ่มใช้งาน บันทึกแล้วระบบจะพาไปหน้าแชต',{exact:true}).waitFor();
  add('signup-otp-password-opens-profile',true);
  await page.locator('body').ariaSnapshot();
  add('blank-profile-cannot-submit',!(await page.locator('form').evaluate(form=>form.checkValidity())));
  await page.evaluate(()=>localStorage.removeItem('nutrition_token'));
  await login('/profile');add('returning-account-without-profile-opens-profile',true);
  await page.locator('body').ariaSnapshot();
  await page.getByLabel('เพศ',{exact:true}).selectOption('male');
  await page.locator('input[name=birth-year]').fill('2000');
  await page.getByLabel('เดือนเกิด',{exact:true}).selectOption('1');
  await page.getByLabel('ส่วนสูง (ซม.)',{exact:true}).fill('175');
  await page.getByLabel('น้ำหนัก (กก.)',{exact:true}).fill('70');
  await page.getByLabel('เล่นเวทกี่วัน/สัปดาห์',{exact:true}).fill('3');
  await page.getByLabel('ระดับกิจกรรมโดยรวม',{exact:true}).selectOption('moderate');
  await page.getByLabel('เป้าหมาย',{exact:true}).selectOption('maintain');
  const failSave=async route=>route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({detail:'Simulated save failure'})});
  await page.route(apiOrigin+'/profile/settings',failSave);
  await page.getByRole('button',{name:'บันทึกและคำนวณ',exact:true}).click();
  await page.getByText('Simulated save failure',{exact:true}).waitFor();
  add('save-failure-stays-on-profile',new URL(page.url()).pathname==='/profile');
  await page.unroute(apiOrigin+'/profile/settings',failSave);
  await page.getByRole('button',{name:'บันทึกและคำนวณ',exact:true}).click();
  await page.waitForURL('**/chat');add('first-profile-save-opens-chat',true);
  await page.evaluate(()=>localStorage.removeItem('nutrition_token'));
  await login('/chat');add('existing-profile-login-opens-chat',true);
  await page.goto(origin+'/profile');await page.getByRole('button',{name:'บันทึกและคำนวณ',exact:true}).waitFor();
  await page.locator('body').ariaSnapshot();
  await page.getByLabel('น้ำหนัก (กก.)',{exact:true}).fill('71');
  await page.getByRole('button',{name:'บันทึกและคำนวณ',exact:true}).click();
  await page.getByText('บันทึกแล้ว',{exact:true}).waitFor();
  add('existing-profile-edit-stays-for-targets',new URL(page.url()).pathname==='/profile');
  await page.screenshot({path:artifactDir+'/saved-profile.png',fullPage:true});
  const failLoad=async route=>route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({detail:'Simulated profile lookup failure'})});
  await page.route(apiOrigin+'/profile',failLoad);
  await page.goto(origin+'/login');await page.locator('body').ariaSnapshot();
  await page.locator('input[name=email]').fill(email);await page.locator('input[name=password]').fill(password);
  await page.locator('button[type=submit]').click();
  await page.getByRole('alert').filter({hasText:'Simulated profile lookup failure'}).waitFor();
  add('lookup-failure-shows-error-without-onboarding',new URL(page.url()).pathname==='/login');
  await page.unroute(apiOrigin+'/profile',failLoad);
  add('no-browser-runtime-errors',errors.length===0);
  return {mode:'Local disposable API and SMTP; real signup/login/profile persistence; injected 500 errors only for failure paths',checks,passed:checks.filter(c=>c.passed).length,failed:checks.filter(c=>!c.passed).length,errors};
}
